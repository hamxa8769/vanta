"""Frozen signal rules (v0.1.0) — pure functions, no I/O.

A signal is advisory / shadow-only. Its SL/TP are generated by THIS
rule from ATR; they are not any institution's levels (those are not
public) and must never be presented as such.

Rules (exact):
    total > +40  -> buy
    total < -40  -> sell
    otherwise    -> none (exactly +/-40 is NO signal)
    entry = current price
    SL  = entry - 1.5*ATR (buy) / entry + 1.5*ATR (sell)
    TP  = entry + 3.0*ATR (buy) / entry - 3.0*ATR (sell)  (2R)
    ATR missing or <= 0 -> ATR = price * 0.01
    confidence = min(0.95, |total|/100 * 0.9 + 0.05) for a signal, else 0
"""

from __future__ import annotations

from datetime import datetime, timezone

from .models import ScoreResult, Signal
from .scoring import RULE_VERSION

BUY_THRESHOLD = 40.0
SELL_THRESHOLD = -40.0
SL_ATR_MULTIPLE = 1.5
TP_ATR_MULTIPLE = 3.0
DEFAULT_ATR_FRACTION = 0.01


def generate_signal(score: ScoreResult, price: float, atr: float | None) -> Signal:
    """Turn a ScoreResult + price + ATR into a frozen advisory Signal."""
    if price is None or price <= 0:
        raise ValueError("price must be a positive number")
    atr_eff = atr if (atr is not None and atr > 0) else price * DEFAULT_ATR_FRACTION
    now = datetime.now(timezone.utc)
    total = score.total

    component_bits = "; ".join(
        f"{c.name} {c.score:+.0f}" for c in score.components
    ) or "no components"
    base_reason = (
        f"Score {total:+.1f} ({score.rule_version}): {component_bits}"
    )

    if total > BUY_THRESHOLD:
        confidence = min(0.95, abs(total) / 100 * 0.9 + 0.05)
        return Signal(
            direction="buy",
            entry=float(price),
            sl=float(price - SL_ATR_MULTIPLE * atr_eff),
            tp=float(price + TP_ATR_MULTIPLE * atr_eff),
            confidence=confidence,
            reason=base_reason
            + f" — above +{BUY_THRESHOLD:.0f} buy threshold; "
            f"SL 1.5xATR, TP 3.0xATR (2R), ATR {atr_eff:.2f}.",
            generated_at=now,
            rule_version=RULE_VERSION,
            horizon_days=10,
            status="open",
        )
    if total < SELL_THRESHOLD:
        confidence = min(0.95, abs(total) / 100 * 0.9 + 0.05)
        return Signal(
            direction="sell",
            entry=float(price),
            sl=float(price + SL_ATR_MULTIPLE * atr_eff),
            tp=float(price - TP_ATR_MULTIPLE * atr_eff),
            confidence=confidence,
            reason=base_reason
            + f" — below {SELL_THRESHOLD:.0f} sell threshold; "
            f"SL 1.5xATR, TP 3.0xATR (2R), ATR {atr_eff:.2f}.",
            generated_at=now,
            rule_version=RULE_VERSION,
            horizon_days=10,
            status="open",
        )
    return Signal(
        direction="none",
        entry=float(price),
        sl=None,
        tp=None,
        confidence=0.0,
        reason=base_reason
        + f" — inside +/-{BUY_THRESHOLD:.0f} band, no signal.",
        generated_at=now,
        rule_version=RULE_VERSION,
        horizon_days=10,
        status="open",
    )
